#!/usr/bin/env python3
"""Converts animation film strips (PNG) into firmware/printdrive/main/anim_data.inc.

States (= file number): 1 ready, 2 upload, 3 download, 4 processing, 5 success, 6 connecting,
7 disconnected, 8 locked, 9 error (see main/anim.h).

Usage:
    python tools/make_anim.py [STRIP_DIR] [--out FILE] [--meta FILE.json] [--ms N] [--preview DIR]

  STRIP_DIR   folder with <nr>_<name>_spritesheet_<W>x40.png, e.g. 01_ready_spritesheet_384x40.png
              (default: firmware/printdrive/main/anim); <nr> = state number 1..9. The older
              names anim_<nr>_<name>.png work as well.
              Each strip is N frames of 48 x 40 px side by side (N*48 x 40), no transparency.
  --out       generated C include (default: firmware/printdrive/main/anim_data.inc);
              it is #included by main/anim.c, so a rebuild is all that is needed.
  --meta      optional JSON with the timing list, e.g.
                [{"file": "02_upload_spritesheet_384x40.png", "ms": 100, "loop": true}]
              (a dict {"<file>": {"ms": 100, "loop": true}} works too; other keys, e.g. the
              designer's manifest.json, are ignored).
              Without an entry: --ms (default 100) and loop = true, except state 5 (success, plays once).
  --preview   also writes a 6x nearest-neighbour GIF per animation into this folder.

Per animation at most 16 colours (the briefing asks for 4). Colours are converted to RGB565, so
two colours that only differ in the low bits count as one. Frames are stored packed 4 bit
(960 bytes per frame) or run-length coded (byte = index << 4 | (run - 1)), whichever is smaller
for the whole animation. Palette index 0 is black if the animation uses black.
Missing states are left empty (the status screen then shows no animation for them).
Prints the flash size used.
"""
import argparse
import json
import re
import sys
from pathlib import Path

from PIL import Image

W, H = 48, 40
ROOT = Path(__file__).resolve().parent.parent
MAIN = ROOT / "firmware" / "printdrive" / "main"
NAMES = {1: "ready", 2: "upload", 3: "download", 4: "processing", 5: "success",
         6: "connecting", 7: "disconnected", 8: "locked", 9: "error"}
ONCE = 5                                  # "success" plays once (after LOCKED -> UNLOCKED)


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def rle(idx):
    out = bytearray()
    i = 0
    while i < len(idx):
        run = 1
        while i + run < len(idx) and idx[i + run] == idx[i] and run < 16:
            run += 1
        out.append((idx[i] << 4) | (run - 1))
        i += run
    return bytes(out)


def pack4(idx):
    return bytes((idx[i] << 4) | idx[i + 1] for i in range(0, len(idx), 2))


def convert(path, nr):
    img = Image.open(path).convert("RGB")
    if img.height != H or img.width % W or img.width == 0:
        sys.exit(f"{path.name}: size {img.width}x{img.height}, expected N*{W} x {H}")
    frames = img.width // W
    if frames > 255:
        sys.exit(f"{path.name}: too many frames")
    raw = img.tobytes()
    px = [tuple(raw[i:i + 3]) for i in range(0, len(raw), 3)]
    cols = {}
    for r, g, b in px:
        cols.setdefault(rgb565(r, g, b), 0)
    pal = sorted(cols, key=lambda c: (c != 0, c))          # black first
    if len(pal) > 16:
        sys.exit(f"{path.name}: {len(pal)} colours (max 16, the briefing asks for 4)")
    lut = {c: i for i, c in enumerate(pal)}
    fr = []
    for f in range(frames):
        idx = [lut[rgb565(*px[y * img.width + f * W + x])] for y in range(H) for x in range(W)]
        fr.append(idx)
    raw = [pack4(i) for i in fr]
    rl = [rle(i) for i in fr]
    use_rle = sum(map(len, rl)) < sum(map(len, raw))
    return pal, (rl if use_rle else raw), use_rle, frames


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("strips", nargs="?", default=str(MAIN / "anim"))
    ap.add_argument("--out", default=str(MAIN / "anim_data.inc"))
    ap.add_argument("--meta")
    ap.add_argument("--ms", type=int, default=100)
    ap.add_argument("--preview")
    a = ap.parse_args()

    meta = {}
    if a.meta:
        m = json.loads(Path(a.meta).read_text(encoding="utf-8"))
        if isinstance(m, list):
            m = {e["file"]: e for e in m}
        elif "states" in m:
            m = {}                    # designer's manifest.json: all frames 100 ms, defaults apply
        meta = m

    files = {}
    for p in sorted(Path(a.strips).glob("*.png")):
        mt = re.fullmatch(r"(?:anim_)?(\d+)_([A-Za-z0-9]+)(?:_spritesheet_\d+x\d+)?\.png", p.name)
        if mt and 1 <= int(mt.group(1)) <= 9:
            files[int(mt.group(1))] = p
    if not files:
        sys.exit(f"no <nr>_<name>_spritesheet_*.png in {a.strips}")

    lines = ["// Generated by tools/make_anim.py - do not edit.",
             "// Included by anim.c (defines anim_def_t, ANIM_COUNT)."]
    entries = {}
    total = 0
    for nr, p in sorted(files.items()):
        pal, frames, use_rle, n = convert(p, nr)
        m = meta.get(p.name, {})
        ms = int(m.get("ms", a.ms))
        loop = bool(m.get("loop", nr != ONCE))
        off, pos = [], 0
        for f in frames:
            off.append(pos)
            pos += len(f)
        data = b"".join(frames)
        size = len(data) + 2 * len(off) + 2 * len(pal)
        total += size
        print(f"{p.name}: {n} frames, {len(pal)} colours, {'RLE' if use_rle else 'packed'}, "
              f"{ms} ms, {'loop' if loop else 'once'}, {size} bytes")
        lines.append(f"static const uint16_t anim{nr}_pal[] = {{{', '.join(f'0x{c:04X}' for c in pal)}}};")
        lines.append(f"static const uint16_t anim{nr}_off[] = {{{', '.join(map(str, off))}}};")
        rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
        lines.append(f"static const uint8_t anim{nr}_data[] = {{\n    " + ",\n    ".join(rows) + "\n};")
        entries[nr] = f"{{ anim{nr}_pal, anim{nr}_data, anim{nr}_off, {n}, {int(use_rle)}, {ms}, {int(loop)} }}"
        if a.preview:
            Path(a.preview).mkdir(parents=True, exist_ok=True)
            strip = Image.open(p).convert("RGB")
            imgs = [strip.crop((f * W, 0, f * W + W, H)).resize((W * 6, H * 6), Image.NEAREST)
                    for f in range(n)]
            gif = Path(a.preview) / (p.stem + ".gif")
            imgs[0].save(gif, save_all=True, append_images=imgs[1:], duration=ms,
                         loop=0 if loop else 1, disposal=1)
    lines.append("static const anim_def_t anim_defs[ANIM_COUNT] = {")
    for nr in range(1, 10):
        lines.append(f"    [{nr}] = {entries.get(nr, '{ 0 }')},   // {NAMES[nr]}")
    lines.append("};")
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"total flash for animation data: {total} bytes -> {a.out}")


if __name__ == "__main__":
    main()
