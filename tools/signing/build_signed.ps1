# Release build: firmware that accepts only signed updates, signed with the owner's key.
#
#   .\tools\signing\build_signed.ps1
#   .\tools\signing\build_signed.ps1 -KeyFile D:\keys\dd.pem
#
# Builds firmware\printdrive into build_signed, always from scratch, from
#   sdkconfig.defaults + sdkconfig.signed + build_signed\sdkconfig.signing_key (key path, generated here)
# ESP-IDF signs build_signed\printdrive.bin during the build (CONFIG_SECURE_BOOT_BUILD_SIGNED_BINARIES).
# Afterwards the file is checked against the key and a copy printdrive-<version>-signed.bin is made.
#
# Flash over USB afterwards: .\tools\flash.ps1 printdrive -Signed
# The normal build (tools\idf.ps1 printdrive build, folder build) stays unsigned and needs no key.
param(
    [string]$KeyFile
)
. (Join-Path $PSScriptRoot 'common.ps1')

$key = Resolve-SigningKey $KeyFile
if (-not (Test-Path $key)) {
    Fail "Signierschlüssel $key nicht gefunden. Einmalig erzeugen: .\tools\signing\new_key.ps1 (oder -KeyFile / `$env:PD_OTA_SIGNING_KEY angeben)."
}
if (Test-InsideRepo $key) {
    Fail "$key liegt im Repository. Bitte den privaten Schlüssel außerhalb des Repositorys aufbewahren."
}
if ($key.Contains('"')) {
    Fail "Der Pfad des Schlüssels darf kein Anführungszeichen enthalten: $key"
}

$projectDir = Join-Path $RepoRoot 'firmware\printdrive'
$buildName = 'build_signed'
$buildDir = Join-Path $projectDir $buildName

# Always from scratch: the configuration comes only from the files above, nothing left over.
if (Test-Path $buildDir) {
    Write-Host "Lösche alten Ordner $buildDir ..."
    Remove-Item -Recurse -Force $buildDir
}
New-Item -ItemType Directory -Force -Path $buildDir | Out-Null

# Third defaults file: only the key path (forward slashes: no escaping needed in sdkconfig).
$overlay = Join-Path $buildDir 'sdkconfig.signing_key'
$keyFwd = $key -replace '\\', '/'
Write-Utf8NoBom $overlay ("# Generated by tools/signing/build_signed.ps1 - local path of the private key`n" +
                          "CONFIG_SECURE_BOOT_SIGNING_KEY=`"$keyFwd`"`n")

Write-Host "== Signierter Build (Schlüssel: $key) =="
Push-Location $projectDir
try {
    $ErrorActionPreference = 'Continue'
    idf.py -B $buildName "-DSDKCONFIG=$buildName/sdkconfig" "-DSDKCONFIG_DEFAULTS=sdkconfig.defaults;sdkconfig.signed;$buildName/sdkconfig.signing_key" build
    $rc = $LASTEXITCODE
    $ErrorActionPreference = 'Stop'
} finally {
    Pop-Location
}
if ($rc -ne 0) { Fail "Build fehlgeschlagen (Exit-Code $rc)." }

# ---------------------------------------------------------------- checks
$sdkconfig = Join-Path $buildDir 'sdkconfig'
foreach ($line in 'CONFIG_PD_OTA_SIGNED=y', 'CONFIG_SECURE_SIGNED_ON_UPDATE_NO_SECURE_BOOT=y',
                  'CONFIG_SECURE_SIGNED_APPS_RSA_SCHEME=y', 'CONFIG_SECURE_BOOT_BUILD_SIGNED_BINARIES=y') {
    if (-not (Select-String -Path $sdkconfig -SimpleMatch -Pattern $line -Quiet)) {
        Fail "$line fehlt in $sdkconfig - das Ergebnis wäre keine Firmware für signierte Updates."
    }
}

$bin = Join-Path $buildDir 'printdrive.bin'
Write-Host "== Prüfe Signatur von $bin =="
if (-not (Test-SignedImage $bin $key)) {
    Fail "$bin ist nicht korrekt signiert. NICHT einspielen."
}

$version = 'unbekannt'
$desc = Join-Path $buildDir 'project_description.json'
if (Test-Path $desc) {
    $version = (Get-Content $desc -Raw | ConvertFrom-Json).project_version
}
$safeVersion = $version -replace '[^A-Za-z0-9._-]', '_'
$release = Join-Path $buildDir "printdrive-$safeVersion-signed.bin"
Copy-Item $bin $release -Force

$info = Get-ImageInfo $bin
$sha = (Get-FileHash $release -Algorithm SHA256).Hash.ToLower()
Write-Host ""
Write-Host "Signierte Firmware $version fertig." -ForegroundColor Green
Write-Host "  Datei:        $release"
Write-Host "  Größe:        $($info.Size) Bytes (Platz im Gerät: 2621440)"
Write-Host "  SHA-256:      $sha"
Write-Host "  Schlüssel-ID: $($info.KeyId)"
Write-Host ""
Write-Host "Einspielen:"
Write-Host "  - über die Weboberfläche (als Admin, 'Gerätesoftware aktualisieren'): die Datei oben"
Write-Host "  - per USB: .\tools\flash.ps1 printdrive -Signed"
Write-Host "NIE build_signed\printdrive-unsigned.bin einspielen (startet nicht, weil unsigniert)."
exit 0
