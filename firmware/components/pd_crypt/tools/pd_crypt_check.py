#!/usr/bin/env python3
"""Host-side checks for the pd_crypt drive encryption (independent re-implementation).

Commands
  vectors              Check the AES-256-XTS known answers in xts_vectors.h (IEEE P1619/D16
                       vectors 10 and 14) with the 'cryptography' package and also verify the
                       mbedtls test data (if found) so the firmware self-test data is trusted.
  gen-vectors DATA     Regenerate xts_vectors.h from mbedtls' test_suite_aes.xts.data.
  inspect IMAGE        Parse and check both header copies of a card image / raw device.
  unlock IMAGE         Derive the keys from --password or --recovery, verify the header tag
                       and decrypt the first volume sectors (expects a FAT boot sector).
                       --out FILE writes the decrypted first --sectors sectors.

IMAGE can be an image file (dd) or a raw device such as \\\\.\\PhysicalDrive2 (Windows, admin)
or /dev/sdX. Only the needed sectors are read.

Needs Python 3.8+; 'cryptography' for vectors/unlock (part of the ESP-IDF Python environment).
"""
import argparse
import hashlib
import hmac
import os
import re
import struct
import sys

SECTOR = 512
MAGIC = b"PDCRYPT1"
HDR_VERSION = 2
HDR_FMT = "<8sHHIQIIII16s"          # up to mk_check, 56 bytes
SLOT_FMT = "<32sII64s32s"           # 136 bytes
SLOT_OFF = (56, 192)
B32 = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
HERE = os.path.dirname(os.path.abspath(__file__))
VECTORS_H = os.path.join(HERE, "..", "xts_vectors.h")


def xts(key, sector, data, encrypt):
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
    c = Cipher(algorithms.AES(key), modes.XTS(sector.to_bytes(16, "little")))
    op = c.encryptor() if encrypt else c.decryptor()
    return op.update(data) + op.finalize()


# ---------------------------------------------------------------- vectors

def parse_mbedtls(path):
    """Return {vector_no: (key, data_unit, pt, ct)} for the AES-256 encrypt vectors 10..14."""
    out = {}
    lines = open(path, encoding="ascii").read().splitlines()
    for i, line in enumerate(lines):
        m = re.match(r"AES-256-XTS Encrypt IEEE P1619/D16 Vector (\d+)$", line)
        if m:
            call = next(l for l in lines[i + 1:i + 4] if l.startswith("aes_encrypt_xts:"))
            key, du, pt, ct = (bytes.fromhex(x) for x in re.findall(r'"([0-9a-fA-F]*)"', call))
            out[int(m.group(1))] = (key, du, pt, ct)
    return out


def gen_vectors(data_path):
    vec = parse_mbedtls(data_path)
    lines = ["// Generated by tools/pd_crypt_check.py gen-vectors from mbedtls'",
             "// tests/suites/test_suite_aes.xts.data (IEEE P1619/D16, XTS-AES-256).",
             "// Key1 = 2718..7627, Key2 = 3141..4592, plaintext = 00 01 .. ff 00 01 .. ff (512 bytes).",
             "#pragma once", "#include <stdint.h>", ""]
    key = vec[10][0]
    lines.append("static const uint8_t XTS_VEC_KEY[64] = {")
    lines += ["    " + ", ".join("0x%02x" % b for b in key[i:i + 16]) + "," for i in range(0, 64, 16)]
    lines.append("};")
    for n in (10, 14):
        k, du, pt, ct = vec[n]
        assert k == key and pt == bytes(range(256)) * 2 and len(ct) == 512
        unit = int.from_bytes(du, "little")
        lines.append("")
        lines.append("#define XTS_VEC%d_UNIT 0x%xULL" % (n, unit))
        lines.append("static const uint8_t XTS_VEC%d_CT[512] = {" % n)
        lines += ["    " + ", ".join("0x%02x" % b for b in ct[i:i + 16]) + "," for i in range(0, 512, 16)]
        lines.append("};")
    open(VECTORS_H, "w", newline="\n").write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(VECTORS_H))


def read_header_vectors():
    src = open(VECTORS_H, encoding="ascii").read()

    def arr(name):
        body = re.search(name + r"\[\d+\] = \{(.*?)\};", src, re.S).group(1)
        return bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", body))

    key = arr("XTS_VEC_KEY")
    res = {}
    for n in (10, 14):
        unit = int(re.search(r"XTS_VEC%d_UNIT 0x([0-9a-f]+)ULL" % n, src).group(1), 16)
        res[n] = (key, unit, arr("XTS_VEC%d_CT" % n))
    return res


def cmd_vectors(args):
    ok = True
    pt = bytes(range(256)) * 2
    for n, (key, unit, ct) in read_header_vectors().items():
        enc = xts(key, unit, pt, True)
        dec = xts(key, unit, ct, False)
        good = enc == ct and dec == pt
        ok &= good
        print("vector %d (data unit 0x%x): %s" % (n, unit, "OK" if good else "FAIL"))
    if args.data and os.path.exists(args.data):
        vec = parse_mbedtls(args.data)
        for n, (key, unit, ct) in read_header_vectors().items():
            same = vec[n][3] == ct and vec[n][0] == key
            ok &= same
            print("vector %d matches mbedtls test data: %s" % (n, "yes" if same else "NO"))
    print("ALL OK" if ok else "FAILED")
    return 0 if ok else 1


# ---------------------------------------------------------------- header

class Dev:
    def __init__(self, path):
        self.f = open(path, "rb", buffering=0)
        self.f.seek(0, os.SEEK_END)
        self.size = self.f.tell()          # raw devices may report 0: use --sectors-total

    def read(self, sector, count=1):
        self.f.seek(sector * SECTOR)
        return self.f.read(count * SECTOR)


def parse_header(raw):
    if len(raw) != SECTOR or raw[:8] != MAGIC:
        return None, "no magic"
    if hashlib.sha256(raw[:480]).digest() != raw[480:]:
        return None, "checksum mismatch"
    f = struct.unpack_from(HDR_FMT, raw, 0)
    h = dict(magic=f[0], version=f[1], sector_size=f[2], flags=f[3], generation=f[4],
             phys=f[5], data_start=f[6], data_sectors=f[7], backup=f[8], mk_check=f[9], raw=raw)
    h["slots"] = [struct.unpack_from(SLOT_FMT, raw, off) for off in SLOT_OFF]
    h["hdr_mac"] = raw[328:360]
    if h["version"] != HDR_VERSION or h["sector_size"] != SECTOR:
        return None, "unsupported version/sector size"
    return h, "ok"


def describe(name, h, why):
    if not h:
        print("%-8s invalid (%s)" % (name, why))
        return
    print("%-8s valid: generation %d, phys %d sectors, volume %d sectors at %d (%.1f MiB), backup @%d,"
          " password slot %d iterations" % (name, h["generation"], h["phys"], h["data_sectors"],
                                            h["data_start"], h["data_sectors"] * SECTOR / 2**20,
                                            h["backup"], h["slots"][0][1]))


def check_geometry(h, why, sectors):
    if h and (h["phys"] != sectors or h["backup"] != sectors - 1 or h["data_start"] < 1 or
              h["data_sectors"] < 2048 or h["data_start"] + h["data_sectors"] > sectors - 1):
        return None, "geometry does not match the medium (%d sectors)" % sectors
    return h, why


def load_headers(path, total):
    dev = Dev(path)
    sectors = total or dev.size // SECTOR
    p_raw = dev.read(0)
    p, pw = check_geometry(*parse_header(p_raw), sectors)
    b, bw, b_raw = (None, "medium size unknown", b"")
    if sectors:
        b_raw = dev.read(sectors - 1)
        b, bw = check_geometry(*parse_header(b_raw), sectors)
    return dev, sectors, (p, pw), (b, bw), p_raw, b_raw


def cmd_inspect(args):
    dev, sectors, (p, pw), (b, bw), p_raw, b_raw = load_headers(args.image, args.sectors_total)
    print("medium: %d sectors (%.2f GiB)" % (sectors, sectors * SECTOR / 2**30))
    describe("primary", p, pw)
    describe("backup", b, bw)
    # Same classification as pd_crypt_attach().
    foreign = p_raw[:8] != MAGIC and p_raw[510:512] == b"\x55\xaa"
    if p or (b and not foreign):
        state = "LOCKED (encrypted)"
    elif foreign:
        state = "PLAIN (sector 0 is an MBR/boot sector%s)" % (", stale backup ignored" if b_raw[:8] == MAGIC else "")
    elif p_raw[:8] == MAGIC or b_raw[:8] == MAGIC:
        state = "DAMAGED (header present, no valid copy)"
    else:
        state = "PLAIN"
    print("firmware would see:", state)
    return 0 if (p or b) else 1


# ---------------------------------------------------------------- unlock

def recovery_bytes(text):
    s = re.sub(r"[\s-]", "", text.upper()).replace("O", "0").replace("I", "1").replace("L", "1")
    if len(s) != 32 or any(c not in B32 for c in s):
        return None
    v = 0
    for c in s:
        v = (v << 5) | B32.index(c)
    return v.to_bytes(20, "big")


def unwrap(slot_index, slot, secret):
    salt, iters, _res, wrapped, tag = slot
    dk = hashlib.pbkdf2_hmac("sha256", secret, salt, iters, 32)
    k_enc = hmac.new(dk, b"pd_crypt enc", hashlib.sha256).digest()
    k_mac = hmac.new(dk, b"pd_crypt mac", hashlib.sha256).digest()
    msg = MAGIC + bytes([slot_index]) + salt + struct.pack("<I", iters) + wrapped
    if not hmac.compare_digest(hmac.new(k_mac, msg, hashlib.sha256).digest(), tag):
        return None
    stream = hmac.new(k_enc, b"\x01", hashlib.sha256).digest() + hmac.new(k_enc, b"\x02", hashlib.sha256).digest()
    return bytes(a ^ b for a, b in zip(wrapped, stream))


def cmd_unlock(args):
    dev, sectors, (p, pw), (b, bw), _, _ = load_headers(args.image, args.sectors_total)
    h = p or b
    if p and b and b["generation"] > p["generation"]:
        h = b
    if not h:
        print("no valid header")
        return 1
    if args.recovery:
        sec = recovery_bytes(args.recovery)
        if sec is None:
            print("recovery key has the wrong format")
            return 1
        mk = unwrap(1, h["slots"][1], sec)
    else:
        mk = unwrap(0, h["slots"][0], args.password.encode("utf-8"))
    if mk is None:
        print("wrong password / recovery key (tag mismatch)")
        return 1
    check = hmac.new(mk, b"pd_crypt mk check", hashlib.sha256).digest()[:16]
    print("master key unwrapped, key check", "OK" if check == h["mk_check"] else "MISMATCH")
    mac = hmac.new(mk, b"pd_crypt hdr" + h["raw"][:56], hashlib.sha256).digest()
    mac_ok = hmac.compare_digest(mac, h["hdr_mac"])
    print("header MAC (geometry authenticated):", "OK" if mac_ok else "MISMATCH")
    check = check if mac_ok else b""
    n = max(1, args.sectors)
    raw = dev.read(h["data_start"], n)
    plain = b"".join(xts(mk, i, raw[i * SECTOR:(i + 1) * SECTOR], False) for i in range(len(raw) // SECTOR))
    sig = plain[510:512] == b"\x55\xaa"
    print("volume sector 0:", "boot signature 55 AA found (MBR/FAT)" if sig else "no boot signature")
    if sig:
        print("  OEM name / type bytes:", plain[3:11], plain[82:90])
    if args.out:
        open(args.out, "wb").write(plain)
        print("wrote %d decrypted sectors to %s" % (len(plain) // SECTOR, args.out))
    return 0 if sig and check == h["mk_check"] else 1


def main():
    ap =argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    v = sub.add_parser("vectors")
    idf = os.environ.get("IDF_PATH", "")
    v.add_argument("--data", default=os.path.join(idf, "components/mbedtls/mbedtls/tests/suites/test_suite_aes.xts.data"))
    g = sub.add_parser("gen-vectors")
    g.add_argument("data")
    for name in ("inspect", "unlock"):
        s = sub.add_parser(name)
        s.add_argument("image")
        s.add_argument("--sectors-total", type=int, default=0, help="medium size in sectors (raw devices)")
        if name == "unlock":
            grp = s.add_mutually_exclusive_group(required=True)
            grp.add_argument("--password")
            grp.add_argument("--recovery")
            s.add_argument("--sectors", type=int, default=8)
            s.add_argument("--out")
    args = ap.parse_args()
    if args.cmd == "gen-vectors":
        gen_vectors(args.data)
        return 0
    return {"vectors": cmd_vectors, "inspect": cmd_inspect, "unlock": cmd_unlock}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
